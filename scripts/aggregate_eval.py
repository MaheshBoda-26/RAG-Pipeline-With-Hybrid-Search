#!/usr/bin/env python3
"""Aggregate chunked eval runs into one benchmark record.

A full golden-set run takes ~20 minutes of judge calls, which is longer than a
single CI step budget, so ``make eval`` may be run in chunks. This script merges
the chunk files into the same numbers a single full run would produce:
judge scores are averaged over *answered* questions, and retrieval metrics are
recomputed from each result's stored relevance flags.

Usage:
    python scripts/aggregate_eval.py /tmp/eval_p*.json
"""
from __future__ import annotations

import argparse
import json
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from tests.eval.metrics import aggregate  # noqa: E402

REPO_URL = "https://github.com/MaheshBoda-26/RAG-Pipeline-With-Hybrid-Search"


def mean(values: list[float | None]) -> float | None:
    valid = [value for value in values if value is not None]
    return statistics.mean(valid) if valid else None


def fmt(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.3f}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("files", nargs="+", help="chunk result JSON files")
    parser.add_argument("--json-out", default="tests/eval/results.json")
    parser.add_argument("--markdown-out", default="docs/benchmarks.md")
    args = parser.parse_args(argv)

    results: list[dict] = []
    for name in args.files:
        payload = json.loads(Path(name).read_text())
        results.extend(payload["results"])

    if not results:
        print("no results found", file=sys.stderr)
        return 1

    answered = [r for r in results if not r["refused"]]
    flags = [r["retrieved_flags"] for r in results if r.get("retrieved_flags")]
    retrieval = aggregate(flags)

    summary = {
        "total_questions": len(results),
        "answered": len(answered),
        "refused": len(results) - len(answered),
        "refusal_rate": (len(results) - len(answered)) / len(results),
        "avg_correctness": mean([r.get("correctness") for r in answered]),
        "avg_faithfulness": mean([r.get("faithfulness") for r in answered]),
        "avg_citation_accuracy": mean([r.get("citation_accuracy") for r in answered]),
        "avg_retrieval_relevance": mean([r.get("retrieval_relevance") for r in answered]),
        "avg_latency_ms": mean([r.get("latency_ms") for r in results]),
        **retrieval,
    }

    Path(args.json_out).write_text(
        json.dumps({"summary": summary, "results": results}, indent=2)
    )

    rows = [
        ("Questions", str(summary["total_questions"])),
        ("Answered", str(summary["answered"])),
        ("Refused", f"{summary['refused']} ({summary['refusal_rate']:.1%})"),
        ("Correctness", fmt(summary["avg_correctness"])),
        ("Faithfulness", fmt(summary["avg_faithfulness"])),
        ("Citation accuracy", fmt(summary["avg_citation_accuracy"])),
        ("Retrieval relevance (judge)", fmt(summary["avg_retrieval_relevance"])),
        ("Recall@1", fmt(summary["recall_at_1"])),
        ("Recall@3", fmt(summary["recall_at_3"])),
        ("Recall@5", fmt(summary["recall_at_5"])),
        ("MRR", fmt(summary["mrr"])),
        ("NDCG@5", fmt(summary["ndcg_at_5"])),
        ("Mean latency (ms)", f"{summary['avg_latency_ms']:.0f}"),
    ]

    markdown = "\n".join(f"| {name} | {value} |" for name, value in rows)
    table = f"| Metric | Value |\n| --- | --- |\n{markdown}"

    benchmark_doc = f"""# Benchmark

Golden set: `tests/eval/golden_set.json` ({summary['total_questions']} questions over the
Aegis demo corpus in `sample_docs/aegis/`).

Reproduce with:

```bash
make eval
```

| Metric | Value |
| --- | --- |
{markdown}

## How to read this

- **Correctness / faithfulness / citation accuracy / retrieval relevance** are
  LLM-judged against the golden answers.
- **Recall@k / MRR / NDCG@5** are judge-free: they check whether the chunk that
  actually contains the golden passage was retrieved, and at what rank. They
  separate retrieval failures from generation failures.
- **Refusals** are counted, not penalised: the pipeline is designed to refuse
  when retrieval confidence is below threshold rather than answer from nothing.

Generated by `scripts/aggregate_eval.py`; raw output: `tests/eval/results.json`.
Repository: {REPO_URL}
"""
    Path(args.markdown_out).write_text(benchmark_doc)

    print(table)
    print(f"\nwrote {args.json_out} and {args.markdown_out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
